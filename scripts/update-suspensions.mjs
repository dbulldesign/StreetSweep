// Regenerate suspensions.json from NYC's official calendar API.
// Runs in GitHub Actions (which can reach api.nyc.gov). Requires the
// NYC_API_KEY secret (free from https://api-portal.nyc.gov/). Writes the
// file ONLY when it parses a sane number of entries, so a bad/blocked
// response never clobbers a good calendar — the app keeps the last commit.

import { writeFileSync } from "node:fs";

const KEY = process.env.NYC_API_KEY;
if (!KEY) {
  console.error("NYC_API_KEY not set — leaving suspensions.json unchanged.");
  process.exit(0); // not a failure; nothing to do without a key
}

const pad = n => String(n).padStart(2, "0");
const fmtUS = d => `${pad(d.getMonth() + 1)}/${pad(d.getDate())}/${d.getFullYear()}`;
const isoDate = d => `${d.getFullYear()}-${pad(d.getMonth() + 1)}-${pad(d.getDate())}`;

const now = new Date();
const years = [now.getFullYear(), now.getFullYear() + 1];

async function getCalendar(from, to) {
  const url = `https://api.nyc.gov/public/api/GetCalendar?fromdate=${encodeURIComponent(fmtUS(from))}&todate=${encodeURIComponent(fmtUS(to))}`;
  const r = await fetch(url, { headers: { "Ocp-Apim-Subscription-Key": KEY } });
  if (!r.ok) throw new Error(`GetCalendar HTTP ${r.status}`);
  return r.json();
}

function parseDate(s) {
  if (!s) return null;
  let m;
  if ((m = /^(\d{4})-(\d{2})-(\d{2})/.exec(s))) return `${m[1]}-${m[2]}-${m[3]}`;
  if ((m = /^(\d{2})\/(\d{2})\/(\d{4})/.exec(s))) return `${m[3]}-${m[1]}-${m[2]}`;
  if ((m = /^(\d{4})(\d{2})(\d{2})$/.exec(s))) return `${m[1]}-${m[2]}-${m[3]}`;
  const d = new Date(s);
  return isNaN(d) ? null : isoDate(d);
}

function cleanLabel(s) {
  const m = /suspended for (.+?)\.?$/i.exec(s);
  return (m ? m[1] : s).replace(/\s+/g, " ").trim() || "ASP suspended";
}

function extractASP(data, out) {
  const days = Array.isArray(data?.days) ? data.days : [];
  for (const day of days) {
    const date = parseDate(day.date || day.today_id);
    if (!date) continue;
    for (const it of (Array.isArray(day.items) ? day.items : [])) {
      if (!String(it.type || "").toLowerCase().includes("alternate side")) continue;
      if (String(it.status || "").toUpperCase().includes("SUSPEND"))
        out.push([date, cleanLabel(String(it.details || it.exceptionName || it.status || "ASP suspended"))]);
    }
  }
}

const collected = [];
for (const y of years) {
  for (let mo = 0; mo < 12; mo += 3) {         // 3-month windows, in case of a range cap
    const from = new Date(y, mo, 1);
    const to = new Date(y, mo + 3, 0);
    try { extractASP(await getCalendar(from, to), collected); }
    catch (e) { console.error(`window ${y}-${pad(mo + 1)}: ${e.message}`); }
  }
}

const seen = new Set(), suspensions = [];
for (const [d, l] of collected.sort((a, b) => a[0].localeCompare(b[0]))) {
  const k = d + "|" + l;
  if (!seen.has(k)) { seen.add(k); suspensions.push([d, l]); }
}

if (suspensions.length < 25) {
  console.error(`Only ${suspensions.length} suspensions parsed — refusing to overwrite (likely incomplete/blocked).`);
  process.exit(1);
}

writeFileSync("suspensions.json", JSON.stringify({
  year: years[0],
  updated: isoDate(now),
  source: "NYC api.nyc.gov GetCalendar (Alternate Side Parking)",
  note: "Auto-generated by scripts/update-suspensions.mjs via GitHub Actions.",
  suspensions
}, null, 2) + "\n");
console.log(`Wrote ${suspensions.length} suspensions for ${years.join(", ")}.`);
